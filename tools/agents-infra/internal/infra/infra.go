func canonicalTargetWrapperBody(entrypoint, goos, targetName string) string {
	// Deprecated aliases refuse directly in the wrapper, before any sibling
	// lookup, build, or exec. Delegating to the local agents-infra launcher
	// would rebuild the Go binary (a filesystem write) before the Go
	// dispatcher could refuse, and a failing toolchain would mask the
	// migration notice with a build error.
	if message, ok := DeprecatedProviderMessage(entrypoint); ok {
		if strings.EqualFold(goos, "windows") {
			return cmdDeprecationRefusalBody(message)
		}
		return posixDeprecationRefusalBody(message)
	}
	if strings.EqualFold(goos, "windows") {
		return fmt.Sprintf("@echo off\r\nsetlocal\r\nset \"DIR=%%~dp0\"\r\nif not exist \"%%DIR%%%s\" (\r\n  echo %s: missing or non-regular sibling %%DIR%%%s 1^>^&2\r\n  exit /b 127\r\n)\r\n\"%%DIR%%%s\" target %s %%*\r\nexit /b %%ERRORLEVEL%%\r\n", targetName, entrypoint, targetName, targetName, entrypoint)
	}
	return fmt.Sprintf(`#!/usr/bin/env sh
set -eu
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
TARGET="$DIR/%s"
if [ ! -f "$TARGET" ] || [ -L "$TARGET" ] || [ ! -x "$TARGET" ]; then
  echo "%s: missing or non-regular sibling $TARGET" >&2
  exit 127
fi
exec "$TARGET" target %s "$@"
`, targetName, entrypoint, entrypoint)
}

